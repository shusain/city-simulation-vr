"""Bake native D129 Editor measurements into a small cooked-safe C++ support table.

Usage: python Tools/Bake-CityBuildingSupports.py <Measurements.json>
This reads geometry evidence only; it never imports or saves Unreal/source assets.
"""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
data = json.loads(source.read_text(encoding="utf-8-sig"))

def simplify(regions):
    # Remove contained rectangles and join only rectangular unions. An L/U wing
    # union therefore never gains support across a courtyard or between legs.
    values = sorted(set(tuple(round(r[k], 3) for k in ("x0", "y0", "x1", "y1", "bottom_z")) for r in regions))
    changed = True
    while changed:
        changed = False
        for i, a in enumerate(values):
            for j, b in enumerate(values):
                if i >= j or abs(a[4] - b[4]) > .01:
                    continue
                merged = (min(a[0], b[0]), min(a[1], b[1]), max(a[2], b[2]), max(a[3], b[3]), a[4])
                area = lambda r: (r[2] - r[0]) * (r[3] - r[1])
                intersection = max(0, min(a[2], b[2]) - max(a[0], b[0])) * max(0, min(a[3], b[3]) - max(a[1], b[1]))
                if abs(area(merged) - (area(a) + area(b) - intersection)) < .1:
                    values = [v for n, v in enumerate(values) if n not in (i, j)] + [merged]
                    changed = True
                    break
            if changed:
                break
    return sorted(set(values))

lines = ["// Generated by Tools/Bake-CityBuildingSupports.py from the reviewed native",
         "// floor measurements in ArtSource/Manifests/city_building_support_measurements.json.",
         "// Units: native mesh-local cm. Flat site pads/paths are excluded."]
for record in data["assets"]:
    name = record["mesh"].split("/")[-1]
    regions = simplify(record["regions_cm"])
    if not regions:
        raise ValueError(f"No structural support measured: {name}")
    lines += [f'if (Name == TEXT("{name}"))', "{", "\tstatic const FCityBuildingSupportRegion Regions[] = {"]
    lines += ["\t\t{" + ", ".join(f"{n:.3f}" for n in r) + "}," for r in regions]
    lines += ["\t};", "\treturn MakeArrayView(Regions);", "}"]
    print(f"{name}: {len(record['regions_cm'])} -> {len(regions)} supports; "
          f"fallbacks={sum(r['fallback'] for r in record['regions_cm'])}; "
          f"parts={[(round(p['width']),round(p['depth']),round(p['height']),round(p['bottom'])) for p in record['selected_parts_cm']]}")
(root / "CitySimVR/Source/CitySimVR/Private/Presentation/CityBuildingSupportData.inl").write_text("\n".join(lines) + "\n", encoding="utf-8")
(root / "ArtSource/Manifests/city_building_support_measurements.json").write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
