"""Generate bounded cosmetic prop/carrier keyframes from accepted Blender scenes."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
doc=json.loads((ROOT/'ArtSource/Manifests/city_park_integration.json').read_text())
sports=json.loads((ROOT/'Artifacts/D83/sports-preview.json').read_text())
records={e['clip']:e for e in sports['scenes']}
order=['Idle','Walk','SkateCarve','SkatePush','SkateKickflip','Skate180','SkateLipStall','BaseballPitch','BaseballSwing',
       'SoccerKick','SoccerRun','GoalkeeperSave','BasketballDribble','BasketballShot']
def numbers(values):return ','.join(f'{v:.8f}f' for v in values)
def pose(p):
    x,y,z=p['position'];w,qx,qy,qz=p['quaternion']
    return '{{'+numbers((x,-y,z))+'},{'+numbers((-qx,qy,-qz,w))+'},{'+numbers(p['scale'])+'}}'
lines=['// Generated by Tools/Generate-CityParkMotionData.py; Blender24fps source.',
       '// Each row is body plus at most two props in imported native space.']
for clip in order:
    e=next(v for v in doc['clips'] if v['name']==clip)
    lines.append('static const FAuthoredParkFrame '+clip+'Frames[] = {')
    for frame in e['frames']:
        props=list(frame['props'])
        while len(props)<2:props.append(dict(position=[0,0,0],quaternion=[1,0,0,0],scale=[0,0,0]))
        lines.append('{'+pose(frame['body'])+',{'+','.join(pose(p) for p in props)+'}},')
    lines.append('};')
lines.append('static const FAuthoredParkClip AuthoredParkClips[] = {')
for clip in order:
    e=next(v for v in doc['clips'] if v['name']==clip)
    props=[]
    for name in records.get(clip,dict(props=[]))['props']:
        kind='Skateboard' if clip.startswith('Skate') else 'Bat' if 'Bat' in name else 'Basketball' if clip.startswith('Basketball') else 'Baseball' if clip.startswith('Baseball') else 'FieldBall'
        props.append('ECityParkActivityProp::'+kind)
    count=len(props)
    while len(props)<2:props.append('ECityParkActivityProp::FieldBall')
    lines.append('{'+clip+'Frames,'+str(e['period'])+','+str(count)+',{' +','.join(props)+'},'+str(e['playback']=='one_shot').lower()+'},')
lines.append('};')
path=ROOT/'CitySimVR/Source/CitySimVR/Private/Presentation/CityParkMotionData.inl'
path.write_text('\n'.join(lines)+'\n')
print('CITYSIM_D83_MOTION_DATA_PASS',len(order),'clips')
