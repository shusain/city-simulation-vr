"""Derive #125 nuclear support strips from the pinned #192 contact vertices.

Original source/export/manifest bytes are never rewritten. Cooling shell strips
follow the32 measured annular sectors instead of filling their square bounds.
"""
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]


def main():
    source = ROOT / 'ArtSource/Manifests/city_nuclear_integration.json'
    doc = json.loads(source.read_text())
    regions = []
    for entry in doc['support_regions']:
        name = entry['component']
        if name.startswith('Open cooling shell'):
            points = [(p[0] * 100, -p[1] * 100) for p in entry['contact_vertices_m']]
            assert len(points) == 64
            cx = sum(p[0] for p in points) / 64
            cy = sum(p[1] for p in points) / 64
            radii = sorted(math.hypot(x-cx, y-cy) for x, y in points)
            inner, outer = sum(radii[:32])/32, sum(radii[32:])/32
            assert abs(inner-489) < .01 and abs(outer-515) < .01
            for index in range(32):
                # The chord rectangle covers one narrow ground-contact sector.
                # At its corners the conservative overhang is less than3cm.
                angle = (index+.5)*math.tau/32
                half = math.pi/32
                radial = (outer+inner)*.5*math.cos(half)
                x, y = cx+radial*math.cos(angle), cy+radial*math.sin(angle)
                yaw = angle+math.pi/2
                ux, uy = x*math.cos(yaw)+y*math.sin(yaw), -x*math.sin(yaw)+y*math.cos(yaw)
                length = 2*outer*math.sin(half)+1
                width = (outer-inner)*math.cos(half)+1
                regions.append(dict(component=name,sector=index,rectangle_cm=[ux-length/2,uy-width/2,ux+length/2,uy+width/2,0],yaw_degrees=math.degrees(yaw)))
        else:
            b = entry.get('bounds_m', dict(min=entry.get('min_m'), max=entry.get('max_m')))
            regions.append(dict(component=name,rectangle_cm=[b['min'][0]*100,-b['max'][1]*100,b['max'][0]*100,-b['min'][1]*100,entry['support_top_z_m']*100],yaw_degrees=0))
    assert len(regions) == 97
    rows = ['// Generated by Write-CityUtilityGroundMetadata.py from pinned #192 contacts.',
            'if(Name==TEXT("Nuclear_v6_Support"))', '{', '    static const FCityBuildingSupportRegion Regions[]={']
    for r in regions:
        rows.append('        {'+','.join(f'{v:.6f}' for v in r['rectangle_cm']+[r['yaw_degrees']])+'}, // '+r['component'])
    rows += ['    };', '    return MakeArrayView(Regions);', '}', '']
    (ROOT/'CitySimVR/Source/CitySimVR/Private/Presentation/CityUtilitySupportData.inl').write_text('\n'.join(rows))
    output = dict(issue=125,integration_issue=192,source_manifest=source.relative_to(ROOT).as_posix(),
                  source_manifest_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                  site_cells=[4,4],native_mapping='x=source.x*100,y=-source.y*100,z=source.z*100; presentation yaw2',
                  support_policy='97 structural/equipment strips including32 per open annular shell; no parcel support',
                  regions=regions)
    (ROOT/'ArtSource/Manifests/city_utility_ground.json').write_text(json.dumps(output,indent=2)+'\n')


if __name__ == '__main__':
    main()
