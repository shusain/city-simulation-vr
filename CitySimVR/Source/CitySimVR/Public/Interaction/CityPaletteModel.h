struct CITYSIMVR_API FCityPaletteEntry
{
	ECityPaletteAction Action = ECityPaletteAction::Close;
	const TCHAR* Label = TEXT("");
	const TCHAR* Help = TEXT("");
	bool bIconOnly = false;
};

// Local Y is viewer-left; local Z is up for the viewer-facing panel.
struct CITYSIMVR_API FCityPaletteRect
{
	FVector Center = FVector::ZeroVector;
	FVector2D HalfSize = FVector2D::ZeroVector;
	bool Contains(const FVector& Point) const
	{
		return FMath::Abs(Point.Y - Center.Y) <= HalfSize.X && FMath::Abs(Point.Z - Center.Z) <= HalfSize.Y;
	}
};

